// Subjects with NO generator in the repo. Pinned deliberately: if a NEW figure appears in one of
// these directories, this harness fails and someone must either write a generator or extend this
// waiver with a reason. Silence is not an option.
//
// DELIBERATELY EMPTY (Biology Slice 0). `biology` was the only entry and it is gone, not blanked:
// its generator is now tools/gen-biology-figures.py and it is in GENERATORS above. Every subject
// that ships figures is therefore generated and reproduced here. An empty waiver makes the loop
// below dormant, not broken — section 2 still fails the moment a figure-bearing subject has no
// generator, because `uncovered` is compared against these (now zero) keys. The red control
// `waiver-wrong-files` SYNTHESISES both sides of that machinery (a waiver entry and a shipped figure
// in the waived subject) so the per-waiver assertion is not decorative while the list is empty.
const KNOWN_NO_GENERATOR = {};

// ---------------------------------------------------------------------------
// Temp sandboxes. Every directory this process creates is registered here and removed in the
// `finally` at the bottom — the controls run by default, so cleanup must survive a thrown control.
const sandboxes = [];
function makeSandbox(prefix = "fig-repro-") {
  const sb = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  sandboxes.push(sb);
  return sb;
}

function runGenerator(gen, sb) {
  const [bin, args] = gen.cmd(sb);
  try {
    const out = execFileSync(bin, args, { cwd: sb, encoding: "utf-8", stdio: ["ignore", "pipe", "pipe"] });
    return { ok: true, out };
  } catch (e) {
    return { ok: false, out: `${e.stdout || ""}${e.stderr || ""}${e.message || ""}` };
  }
}

/** Run one generator into a fresh sandbox and read back the bytes it produced. */
function runAndRead(gen) {
  const sb = makeSandbox();
  gen.prepare(sb);
  const run = runGenerator(gen, sb);
  const dir = gen.outDir(sb);
  return { ok: run.ok, out: run.out, dir, entries: run.ok ? readEntries(dir) : [] };
}

// Each generator is invoked ONCE per process and the result reused. §1 compares that real run; the
// six byte-flip controls flip a COPY of those same bytes rather than re-running the generator six
// more times, so defaulting the controls on costs ONE extra generator invocation (the perturbed
// H&SB), not seven. Keyed by path + subject so two generators can never share a result.
const RUN_CACHE = new Map();
function producedOf(gen) {
  const key = `${gen.generator}|${gen.subject}`;
  if (!RUN_CACHE.has(key)) RUN_CACHE.set(key, runAndRead(gen));
  return RUN_CACHE.get(key);
}

// Compare one generator's output against the shipped trees under `root`. Returns {checked, mismatches[]}.
// `root` is a parameter, not the module-level ROOT, so a control can point the comparison at a
// sandboxed copy of the two trees and mutate that instead of the real one.
function compare(gen, root, label = "") {
  const run = gen.__run || producedOf(gen);
  const generated = run.entries.map((e) => e.name);
  const mismatches = [];
  let checked = 0;
  if (generated.length === 0) {
    return { checked: 0, mismatches: [`${label}${gen.generator} produced no SVGs in ${run.dir}`] };
  }
  for (const entry of run.entries) {
    checked++;
    for (const tree of TREES) {
      const shippedPath = path.join(root, tree, gen.subject, "figures", entry.name);
      const shipped = readSvg(shippedPath);
      if (!shipped) {
        mismatches.push(`${label}${tree}/${gen.subject}/figures/${entry.name} is generated by ${gen.generator} but is not shipped`);
        continue;
      }
      const shippedMd5 = md5(shipped);
      if (shippedMd5 !== entry.md5) {
        mismatches.push(`${label}${tree}/${gen.subject}/figures/${entry.name} DRIFTED from ${gen.generator}: ` +
                        `shipped ${shippedMd5.slice(0, 12)} != regenerated ${entry.md5.slice(0, 12)}`);
      }
    }
  }
  // Every shipped figure in a generated subject must be produced by its generator.
  for (const name of svgNames(path.join(root, CONTENT, gen.subject, "figures"))) {
    if (!generated.includes(name)) {
      mismatches.push(`${label}${gen.subject}/figures/${name} is shipped but ${gen.generator} does not generate it`);
    }
  }
  return { checked, mismatches };
}

// Snapshot every shipped figure under `root`. The comparison in §3 is the harness proving its own
// non-destructiveness, rather than asking the reader to trust a comment.
function snapshotShipped(root) {
  const snap = {};
  for (const tree of TREES) {
    const base = path.join(root, tree);
    if (!fs.existsSync(base)) continue;
    for (const subject of fs.readdirSync(base)) {
      for (const name of svgNames(path.join(base, subject, "figures"))) {
        const f = path.join(base, subject, "figures", name);
        snap[`${tree}/${subject}/figures/${name}`] = md5(fs.readFileSync(f));
      }
    }
  }
  return snap;
}

// ---------------------------------------------------------------------------
// state: everything the checks read, loaded once and mutated by the red controls.
// `snapshotShipped` is on the state so a control can replace it — that is the only way to make §3's
// "nothing was touched" comparison fail honestly, and the default is the real function above.
function loadState() {
  return {
    root: ROOT,
    generators: GENERATORS.map((g) => ({ ...g })),
    knownNoGenerator: JSON.parse(JSON.stringify(KNOWN_NO_GENERATOR)),
    snapshotShipped,
  };
}

// ---------------------------------------------------------------------------
// The real check. Pure with respect to `st`: it prints nothing, returns everything, and is run once
// for the report and once per red control. `failures` holds assertion messages only; section headers
// are kept in `trace` so they can never be counted as assertions.
function runChecks(st) {
  let pass = 0;
  const failures = [];
  const trace = [];
  const check = (cond, msg) => {
    if (cond) { pass++; trace.push(`  ok   ${msg}`); }
    else { failures.push(msg); trace.push(`  FAIL ${msg}`); }
  };
  const eq = (actual, expected, msg) => {
    const same = JSON.stringify(actual) === JSON.stringify(expected);
    check(same, same ? msg : `${msg} — got ${JSON.stringify(actual)}, expected ${JSON.stringify(expected)}`);
  };
  const section = (t) => { trace.push(`\n${t}`); };
  const note = (t) => trace.push(`       ${t}`);
  let totalFigures = 0;

  // Snapshot before a single generator runs.
  const before = st.snapshotShipped(st.root);

  section("1. every generator reproduces the figures shipped in both trees");
  for (const gen of st.generators) {
    // A control may hand over its own run (`__run`) or ask for a fresh one (`__noCache`: a generator
    // that crashes or writes nothing). Everything else reuses the one real run of that generator.
    if (!gen.__run && gen.__noCache) gen.__run = runAndRead(gen);
    const run = gen.__run || producedOf(gen);
    if (!run.ok) {
      check(false, `${gen.generator} failed to run: ${String(run.out).trim().split("\n").slice(-3).join(" | ")}`);
      continue;
    }
    const { checked, mismatches } = compare(gen, st.root);
    totalFigures += checked;
    check(mismatches.length === 0 && checked > 0,
          `${gen.subject}: ${gen.generator} reproduces all ${checked} shipped figure(s) in both trees` +
          (mismatches.length ? `\n         ${mismatches.join("\n         ")}` : ""));
    note(`(${String(run.out).trim().split("\n").filter((l) => l.startsWith("wrote")).join("; ") || "ran"})`);
  }

  section("2. the figure family is fully accounted for (no silent gaps)");
  const subjectsWithFigures = fs
    .readdirSync(path.join(st.root, CONTENT))
    .filter((s) => svgNames(path.join(st.root, CONTENT, s, "figures")).length > 0)
    .sort();
  const generatedSubjects = st.generators.map((g) => g.subject).sort();
  const uncovered = {};
  for (const s of subjectsWithFigures) {
    if (!generatedSubjects.includes(s)) uncovered[s] = svgNames(path.join(st.root, CONTENT, s, "figures"));
  }
  eq(Object.keys(uncovered).sort(), Object.keys(st.knownNoGenerator).sort(),
     "exactly the expected subjects have no generator");
  for (const [s, waive] of Object.entries(st.knownNoGenerator)) {
    eq(uncovered[s] || [], waive.files,
       `${s}: its ${waive.files.length} shipped figure(s) are the waived, generator-less set`);
    note(`(${s}: ${waive.reason})`);
  }
  const covered = subjectsWithFigures.filter((s) => generatedSubjects.includes(s));
  note(`covered by a generator: ${covered.join(", ")}`);
  note(`waived (no generator): ${Object.keys(st.knownNoGenerator).join(", ") || "(none — every figure-bearing subject has a generator)"}`);
  check(subjectsWithFigures.length === covered.length + Object.keys(st.knownNoGenerator).length,
        `every subject that ships figures is covered or explicitly waived (${subjectsWithFigures.length} subjects)`);

  section("3. the run did not touch the shipped figures (non-destructiveness, asserted)");
  const after = st.snapshotShipped(st.root);
  // Without this, a snapshot that came back empty would make both comparisons below `0 === 0` and
  // `[] === []` and pass: the red control `snapshot-broken` proves this line is load-bearing.
  check(Object.keys(before).length > 0,
        "the pre-run snapshot found the shipped figures to compare against");
  eq(Object.keys(after).length, Object.keys(before).length, "the same figures exist after the run");
  const touched = Object.keys(before).filter((k) => after[k] !== before[k]);
  eq(touched, [], `no shipped figure was modified by running the generators (${Object.keys(before).length} checked)`);
  // Reads the process-wide registry deliberately: the claim is about EVERY sandbox this run made.
  for (const sb of sandboxes) {
    check(sb.startsWith(os.tmpdir()), `sandbox ${path.basename(sb)} is inside ${os.tmpdir()}`);
  }
  note("(every generator got an explicit output dir; --trees is never passed. If a generator");
  note(" were run in a tree-writing mode, the md5 comparison above would fail.)");

  return { pass, failures, totalFigures, trace };
}

// ---------------------------------------------------------------------------
// red controls: each mutates the loaded state (never the real tree) and MUST make runChecks fail.
// A control may return `{ pins: [...] }` when the message it is aimed at can only be known at run
// time (the name of the first generated figure); RED_EXPECT holds the static pins.

/** A sandboxed COPY of both trees' figure directories, for controls that mutate what is shipped. */
function fakeRoot() {
  const root = makeSandbox("fig-fakeroot-");
  for (const tree of TREES) {
    const base = path.join(ROOT, tree);
    if (!fs.existsSync(base)) continue;
    for (const subject of fs.readdirSync(base)) {
      const figs = path.join(base, subject, "figures");
      if (svgNames(figs).length === 0) continue;
      fs.cpSync(figs, path.join(root, tree, subject, "figures"), { recursive: true });
    }
  }
  return root;
}

/** A copy of one generator's generated output, ready to be perturbed without touching the cache. */
function copyGenerated(gen) {
  const base = producedOf(gen);
  if (!base.ok) throw new Error(`${gen.generator} did not run, so its output cannot be probed`);
  if (!base.entries.length) throw new Error(`${gen.generator} produced no SVGs to probe`);
  const dir = makeSandbox("fig-flip-");
  fs.cpSync(base.dir, dir, { recursive: true });
  return { base, dir };
}

/** One control per generator: a single byte changed in its output must be caught, in BOTH trees. */
function byteFlip(subject) {
  return (st) => {
    const gen = st.generators.find((g) => g.subject === subject);
    if (!gen) throw new Error(`no generator for ${subject} to probe`);
    const { base, dir } = copyGenerated(gen);
    const name = base.entries[0].name;
    const f = path.join(dir, name);
    const buf = fs.readFileSync(f);
    buf[buf.length - 3] = buf[buf.length - 3] ^ 0x01; // one byte, inside the trailing newline region
    fs.writeFileSync(f, buf);
    gen.__run = { ...base, dir, entries: readEntries(dir) };
    return {
      pins: [`${CONTENT}/${subject}/figures/${name} DRIFTED from ${gen.generator}`,
             `${PUBLIC}/${subject}/figures/${name} DRIFTED from ${gen.generator}`],
    };
  };
}

const HSB_CELL = "hsb-plant-and-animal-cell.svg";

const RED_CONTROLS = {
  // (a) the incident itself: move H&SB's lower mitochondrion by 1px in a sandboxed COPY of the
  //     generator, and require exactly the cell figure to be reported as drifted, in both trees.
  "hsb-perturbed": (st) => {
    const hsb = st.generators.find((g) => g.subject === "human-social-biology");
    if (!hsb) throw new Error("no human-social-biology generator to perturb");
    const src = fs.readFileSync(path.join(ROOT, "tools/gen-human-social-biology-figures.py"), "utf-8");
    // Locate the line rather than hard-coding a coordinate: the shipped y differs between main and
    // the #179 branch, and a red control that only works on one of them proves nothing.
    const m = src.match(/mitochondrion\(352, (\d+), 100, 48\)/);
    if (!m) throw new Error("could not find the H&SB lower-mitochondrion line to perturb");
    const needle = m[0];
    const perturbed = src.replace(needle, `mitochondrion(352, ${Number(m[1]) + 1}, 100, 48)`);
    if (perturbed === src) throw new Error("the perturbation did not change the generator source");
    const toolDir = makeSandbox("fig-perturb-");
    const copy = path.join(toolDir, "gen-human-social-biology-figures.py");
    fs.writeFileSync(copy, perturbed);
    const run = runAndRead({ ...hsb, cmd: (s) => ["python3", [copy, "--repo", ROOT, "--out", hsb.outDir(s)]] });
    // Kept from the original file, and the best idea in it: if the perturbed generator crashes, the
    // run would fail for the wrong reason. That is a broken fixture, not a caught control.
    if (!run.ok) throw new Error(`the perturbed generator did not run (${String(run.out).trim().slice(0, 120)})`);
    // The fixture must differ in exactly the one figure, or "only that figure drifts" is not a fact.
    const base = producedOf(hsb);
    const changed = run.entries.filter((e) => {
      const b = base.entries.find((x) => x.name === e.name);
      return !b || b.md5 !== e.md5;
    });
    if (changed.length !== 1 || changed[0].name !== HSB_CELL) {
      throw new Error(`the perturbation changed ${changed.length} figure(s) (${changed.map((c) => c.name).join(", ")}), not only ${HSB_CELL}`);
    }
    hsb.__run = run;
    return {
      pins: [`${CONTENT}/human-social-biology/figures/${HSB_CELL} DRIFTED`,
             `${PUBLIC}/human-social-biology/figures/${HSB_CELL} DRIFTED`],
    };
  },
  // (b) every generator's comparison path bites: flip one byte of one generated file. Each pins BOTH
  //     tree lines, so reducing the tree loop in compare() to [CONTENT] reds all six.
  "byte-flip-biology": byteFlip("biology"),
  "byte-flip-human-social-biology": byteFlip("human-social-biology"),
  "byte-flip-integrated-science": byteFlip("integrated-science"),
  "byte-flip-chemistry": byteFlip("chemistry"),
  "byte-flip-physics": byteFlip("physics"),
  "byte-flip-mathematics": byteFlip("mathematics"),
  // (c) §1's "generated but not shipped" half. The file is deleted from the PUBLIC tree only, so the
  //     content tree still matches: a check that were satisfied by one good tree would report nothing.
  "generated-not-shipped": (st) => {
    const gen = st.generators.find((g) => g.subject === "biology");
    const name = producedOf(gen).entries[0].name;
    st.root = fakeRoot();
    fs.rmSync(path.join(st.root, PUBLIC, "biology", "figures", name));
    return { pins: [`${PUBLIC}/biology/figures/${name} is generated by ${gen.generator} but is not shipped`] };
  },
  // (d) §1's "shipped but not generated" half.
  "shipped-not-generated": (st) => {
    const extra = "red-control-extra.svg";
    st.root = fakeRoot();
    fs.writeFileSync(path.join(st.root, CONTENT, "biology", "figures", extra), "<svg/>");
    return { pins: [`biology/figures/${extra} is shipped but tools/gen-biology-figures.py does not generate it`] };
  },
  // (e) a generator that runs cleanly and writes nothing.
  "generator-produces-nothing": (st) => {
    const i = st.generators.findIndex((g) => g.subject === "biology");
    st.generators[i] = { ...st.generators[i], __noCache: true, cmd: () => ["node", ["-e", "process.exit(0)"]] };
    return { pins: ["tools/gen-biology-figures.py produced no SVGs in"] };
  },
  // (f) a generator that crashes.
  "generator-crash": (st) => {
    const i = st.generators.findIndex((g) => g.subject === "biology");
    st.generators[i] = { ...st.generators[i], __noCache: true, cmd: () => ["node", ["-e", "process.exit(3)"]] };
    return { pins: ["tools/gen-biology-figures.py failed to run"] };
  },
  // (g) a subject that ships a figure and has no generator — the KNOWN_NO_GENERATOR list is empty, so
  //     this is the only way to make §2's population comparison reject something.
  "uncovered-subject": (st) => {
    st.root = fakeRoot();
    const dir = path.join(st.root, CONTENT, "agriculture-double-option", "figures");
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "red-control-orphan.svg"), "<svg/>");
    return { pins: ["exactly the expected subjects have no generator"] };
  },
  // (h) the waiver machinery, both sides synthesised: a waiver entry exists AND the waived subject
  //     ships a figure, but the names disagree. §2's per-waiver assertion is what must catch it.
  "waiver-wrong-files": (st) => {
    st.root = fakeRoot();
    const dir = path.join(st.root, CONTENT, "agriculture-double-option", "figures");
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "waived-but-different.svg"), "<svg/>");
    st.knownNoGenerator = {
      "agriculture-double-option": { files: ["the-waived-name.svg"], reason: "synthesised by the red control" },
    };
    return { pins: ["agriculture-double-option: its 1 shipped figure(s) are the waived, generator-less set"] };
  },
  // (i) §3: a figure whose bytes changed during the run. The first snapshot is the real one; the
  //     second reports one figure rewritten, which is what a tree-writing generator would leave behind.
  "figure-touched": (st) => {
    const real = snapshotShipped;
    let calls = 0;
    st.snapshotShipped = (root) => {
      const snap = real(root);
      if (calls++ === 0) return snap;
      const k = Object.keys(snap)[0];
      if (k) snap[k] = md5(Buffer.from("this figure was rewritten by a generator"));
      return snap;
    };
    return { pins: ["no shipped figure was modified by running the generators"] };
  },
  // (j) §3 vacuity: an empty snapshot made both comparisons pass before 2026-11-21.
  "snapshot-broken": (st) => {
    st.snapshotShipped = () => ({});
    return { pins: ["the pre-run snapshot found the shipped figures to compare against"] };
  },
};

// ---------------------------------------------------------------------------
// What each control must be caught BY — one ARRAY per control. A control that synthesises state
// trips more than one assertion at once (adding a figure to a fake root also moves §3's figure
// count), so "some failure appeared" is not proof that the assertion the control is FOR still checks
// anything: a control whose guard had been deleted would still report caught because a DIFFERENT
// assertion tripped. The run only passes if every message listed here is among the failures.
// A control with no entry here fails outright as unpinned (runControl), so a later edit cannot add a
// control and leave it aimed at nothing. Controls that mutate a generator return their pins instead
// (see RED_CONTROLS), because the figure name they are aimed at is only known at run time.
const RED_EXPECT = {
  // §1's "generated but not shipped" line, PUBLIC tree only.
  "generated-not-shipped": ["is generated by tools/gen-biology-figures.py but is not shipped"],
  // §1's "shipped but not generated" line.
  "shipped-not-generated": ["is shipped but tools/gen-biology-figures.py does not generate it"],
  // §1's empty-output branch.
  "generator-produces-nothing": ["produced no SVGs in"],
  // §1's crash branch.
  "generator-crash": ["failed to run"],
  // §2's population comparison.
  "uncovered-subject": ["exactly the expected subjects have no generator"],
  // §2's per-waiver file-set assertion.
  "waiver-wrong-files": ["are the waived, generator-less set"],
  // §3's touched list.
  "figure-touched": ["no shipped figure was modified by running the generators"],
  // §3's new non-empty-snapshot assertion.
  "snapshot-broken": ["the pre-run snapshot found the shipped figures"],
};

// ---------------------------------------------------------------------------
/** Run one control against a fresh load. ok = it was caught, and caught by the assertion it names. */
function runControl(name) {
  const st = loadState();
  const returned = RED_CONTROLS[name](st) || {};
  const expect = [...(RED_EXPECT[name] || []), ...(returned.pins || [])];
  const { failures } = runChecks(st);
  const real = failures.filter((f) => !f.startsWith("\u0000"));
  if (!real.length) return { ok: false, real, why: "WAS NOT CAUGHT — the check is blind to it" };
  if (!expect.length) return { ok: false, real, why: "NO PINNED EXPECTATION — this control is not aimed at any assertion" };
  const missing = expect.filter((e) => !real.some((f) => f.includes(e)));
  if (missing.length) return { ok: false, real, why: `CAUGHT BY THE WRONG ASSERTION — no failure containing "${missing[0]}"` };
  return { ok: true, real: real.filter((f) => expect.some((e) => f.includes(e))) };
}

// ---------------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);
  const only = argv.includes("--red-control") ? argv[argv.indexOf("--red-control") + 1] : null;
  const started = Date.now();

  if (only) {
    if (!RED_CONTROLS[only]) { console.log(`unknown red control: ${only}`); return 2; }
    let r;
    try { r = runControl(only); }
    catch (e) { console.log(`RED CONTROL "${only}" BROKE — ${e.message}`); return 1; }
    if (!r.ok) {
      console.log(`RED CONTROL "${only}" ${r.why}`);
      r.real.slice(0, 3).forEach((f) => console.log(`   ${f}`));
      return 1;
    }
    console.log(`red control "${only}": caught — as expected`);
    r.real.slice(0, 3).forEach((f) => console.log(`   ${f}`));
    return 0;
  }

  const real = runChecks(loadState());
  for (const line of real.trace) console.log(line);
  const realFailures = real.failures.length;
  console.log(`\nfigures reproduced by their generators: ${real.totalFigures}`);

  if (argv.includes("--no-red-control")) {
    console.log(`\ncheck-figure-generators: ${real.pass} checks passed, ${realFailures} failed (red controls skipped by --no-red-control)`);
    console.log(`runtime: ${((Date.now() - started) / 1000).toFixed(1)}s`);
    return realFailures ? 1 : 0;
  }

  // Red controls run by DEFAULT — the suite passes no arguments, so this is the path it takes.
  let bad = 0;
  for (const name of Object.keys(RED_CONTROLS)) {
    let r;
    try { r = runControl(name); }
    catch (e) { bad++; console.log(`BROKEN: ${name} — ${e.message}`); continue; }
    if (!r.ok) { bad++; console.log(`${r.real.length ? "WRONG ASSERTION" : "NOT CAUGHT"}: ${name} — ${r.why}`); }
    else console.log(`caught (${r.real.length}): ${name} — ${r.real[0]}`);
  }
  console.log(`${Object.keys(RED_CONTROLS).length} red controls, ${bad} not caught`);
  console.log(`\ncheck-figure-generators: ${real.pass} checks passed, ${realFailures} failed · ` +
              `${Object.keys(RED_CONTROLS).length} red controls, ${bad} not caught`);
  console.log(`runtime: ${((Date.now() - started) / 1000).toFixed(1)}s`);
  if (realFailures > 0) {
    console.log("\nA drift here means a generator no longer reproduces the shipped figure. Re-run the");
    console.log("generator (in its temp-output mode), or fix the generator — never hand-edit the SVG");
    console.log("to match the generator, which is what this harness exists to prevent.");
  }
  // ONE exit code for both halves: a failing real check and an uncaught control are both red.
  return realFailures || bad ? 1 : 0;
}

let code;
try {
  code = main();
} finally {
  for (const sb of sandboxes) fs.rmSync(sb, { recursive: true, force: true });
}
process.exit(code);
