#!/usr/bin/env node
// Figure generators are part of the figure.
//
// WHY THIS EXISTS
// The rule "generators must be byte-reproducible" was convention, not a gate. In PR #179 a merged
// artwork fix was undone in the generator of record and nothing noticed: no harness regenerated or
// checked any figure, so a normal repo action could silently revert a fix into a live lesson. This
// harness turns that convention into a gate: it re-runs every figure generator and byte-compares its
// output against the SVGs actually committed in both trees.
//
// WHAT IT PROVES
//   - for every subject that HAS a generator, re-running that generator reproduces the shipped
//     `content/<subject>/figures/*.svg` and `public/content/<subject>/figures/*.svg` byte for byte;
//   - the set of shipped figures is exactly accounted for: every figure is either generated by the
//     subject's generator, or named in KNOWN_NO_GENERATOR below with a reason. A new figure that
//     nothing generates FAILS this harness until someone either writes its generator or waives it —
//     so coverage can only grow deliberately.
//
// WHAT IT DOES NOT PROVE (read this before trusting a green run)
//   - It proves the generators reproduce the CURRENTLY COMMITTED figures. That is NOT the same as
//     proving those figures are correct: a wrong-but-reproducible figure passes here. Geometry
//     correctness is a different instrument (see tools/check-lesson-figures.mjs for the schema and
//     the containment tooling under docs/screenshots/shared-cell-artwork/ for the artwork).
//   - It cannot see a figure that was hand-edited to match no generator: that shows up as a
//     mismatch (good) only for subjects that have a generator. For a subject in
//     KNOWN_NO_GENERATOR there is nothing to reproduce against, so its figures are unverified here.
//   - It does not check that a figure is referenced by a lesson, assembled into a page, or rendered.
//   - It would not notice a generator that is wrong in the same way in both trees (they are
//     compared to each other's sources and to the generator, not to an independent oracle).
//   - Runtime is seconds; see the tail of the run for the measured cost.
//
// Non-destructive by construction: every generator is invoked with an explicit output directory
// inside a temp sandbox, and the sandbox is removed afterwards. The harness refuses to run a
// generator in a mode that writes the trees (see runGenerator: --trees is never passed, and the
// generators whose default mode writes the trees are always given an explicit output).
//
// Usage:
//   node tools/check-figure-generators.mjs               green run
//   node tools/check-figure-generators.mjs --red-control proves the guard bites (see below)
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const CONTENT = "content";
const PUBLIC = "public/content";
const RED_CONTROL = process.argv.includes("--red-control");

let pass = 0;
let fail = 0;
const failures = [];
function ok(cond, msg) {
  if (cond) { pass++; console.log(`  ok   ${msg}`); }
  else { fail++; failures.push(msg); console.log(`  FAIL ${msg}`); }
}
function eq(actual, expected, msg) {
  const same = JSON.stringify(actual) === JSON.stringify(expected);
  ok(same, same ? msg : `${msg} — got ${JSON.stringify(actual)}, expected ${JSON.stringify(expected)}`);
}
function section(t) { console.log(`\n${t}`); }

const md5 = (buf) => crypto.createHash("md5").update(buf).digest("hex");
const readSvg = (p) => (fs.existsSync(p) ? fs.readFileSync(p) : null);
const svgNames = (dir) =>
  (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort() : []);

// ---------------------------------------------------------------------------
// The figure family. Each entry must be run in a mode that writes ONLY `outDir`.
// `prepare` copies anything the generator needs into the sandbox, so no run can
// reach back into the working tree to write.

const sandboxOut = (sb, subject) => path.join(sb, "content", subject, "figures");

const GENERATORS = [
  {
    subject: "human-social-biology",
    generator: "tools/gen-human-social-biology-figures.py",
    // --out wins unless --trees is passed (main(): outs=[--out]; only --trees replaces it).
    // --repo is a READ (Biology's heart, byte-compared inside the generator); never pass --trees.
    cmd: (sb) => ["python3", [path.join(ROOT, "tools/gen-human-social-biology-figures.py"),
                              "--repo", ROOT, "--out", sandboxOut(sb, "human-social-biology")]],
    outDir: (sb) => sandboxOut(sb, "human-social-biology"),
    prepare: () => {},
  },
  {
    subject: "integrated-science",
    generator: "tools/gen-integrated-science-figures.py",
    // --out wins; without it the generator writes the trees when --root holds the modules file,
    // so an explicit --out is mandatory here.
    cmd: (sb) => ["python3", [path.join(ROOT, "tools/gen-integrated-science-figures.py"),
                              "--root", ROOT, "--out", sandboxOut(sb, "integrated-science")]],
    outDir: (sb) => sandboxOut(sb, "integrated-science"),
    prepare: () => {},
  },
  {
    subject: "chemistry",
    generator: "tools/gen-chemistry-figures.py",
    // No CLI at all: it derives ROOT from its own file location, so copying it into <sb>/tools/
    // makes it write <sb>/content/... — the only way to run it without touching the tree.
    cmd: (sb) => ["python3", [path.join(sb, "tools", "gen-chemistry-figures.py")]],
    outDir: (sb) => sandboxOut(sb, "chemistry"),
    prepare: (sb) => {
      fs.mkdirSync(path.join(sb, "tools"), { recursive: true });
      fs.copyFileSync(path.join(ROOT, "tools/gen-chemistry-figures.py"),
                      path.join(sb, "tools", "gen-chemistry-figures.py"));
    },
  },
  {
    subject: "physics",
    generator: "tools/gen-physics-figures.mjs",
    // argv[2] is an outdir; without it the generator writes both trees when run from a repo root.
    cmd: (sb) => ["node", [path.join(ROOT, "tools/gen-physics-figures.mjs"),
                           sandboxOut(sb, "physics")]],
    outDir: (sb) => sandboxOut(sb, "physics"),
    prepare: () => {},
  },
];

// Subjects with NO generator in the repo. Pinned deliberately: if a NEW figure appears in one of
// these directories, this harness fails and someone must either write a generator or extend this
// waiver with a reason. Silence is not an option.
const KNOWN_NO_GENERATOR = {
  biology: {
    files: ["heart-and-double-circulation.svg", "kidney-and-nephron.svg", "plant-and-animal-cell.svg"],
    reason: "hand-authored; there is no biology generator in tools/. Its figures are the read-only " +
            "sources other generators borrow (H&SB copies the heart byte-for-byte, IS asserts the " +
            "cell's wall/blob/mitochondrion/Golgi/leader geometry against them), so drift there is " +
            "caught indirectly by those two generators, not here.",
  },
};

function makeSandbox() {
  return fs.mkdtempSync(path.join(os.tmpdir(), "fig-repro-"));
}

function runGenerator(gen, sb) {
  const [bin, args] = gen.cmd(sb);
  try {
    const out = execFileSync(bin, args, { cwd: sb, encoding: "utf-8", stdio: ["ignore", "pipe", "pipe"] });
    return { ok: true, out };
  } catch (e) {
    return { ok: false, out: `${e.stdout || ""}${e.stderr || ""}${e.message || ""}` };
  }
}

// Compare one generator's output against the shipped trees. Returns {checked, mismatches[]}.
function compare(gen, sb, label = "") {
  const genDir = gen.outDir(sb);
  const generated = svgNames(genDir);
  const mismatches = [];
  let checked = 0;
  if (generated.length === 0) {
    return { checked: 0, mismatches: [`${label}${gen.generator} produced no SVGs in ${genDir}`] };
  }
  for (const name of generated) {
    checked++;
    const produced = md5(fs.readFileSync(path.join(genDir, name)));
    for (const tree of [CONTENT, PUBLIC]) {
      const shippedPath = path.join(ROOT, tree, gen.subject, "figures", name);
      const shipped = readSvg(shippedPath);
      if (!shipped) {
        mismatches.push(`${tree}/${gen.subject}/figures/${name} is generated by ${gen.generator} but is not shipped`);
        continue;
      }
      const shippedMd5 = md5(shipped);
      if (shippedMd5 !== produced) {
        mismatches.push(`${tree}/${gen.subject}/figures/${name} DRIFTED from ${gen.generator}: ` +
                        `shipped ${shippedMd5.slice(0, 12)} != regenerated ${produced.slice(0, 12)}`);
      }
    }
  }
  // Every shipped figure in a generated subject must be produced by its generator.
  for (const name of svgNames(path.join(ROOT, CONTENT, gen.subject, "figures"))) {
    if (!generated.includes(name)) {
      mismatches.push(`${gen.subject}/figures/${name} is shipped but ${gen.generator} does not generate it`);
    }
  }
  return { checked, mismatches };
}

const started = Date.now();
const sandboxes = [];
let totalFigures = 0;

// Snapshot every shipped figure before a single generator runs. The comparison below is the
// harness proving its own non-destructiveness, rather than asking the reader to trust a comment.
function snapshotShipped() {
  const snap = {};
  for (const tree of [CONTENT, PUBLIC]) {
    const base = path.join(ROOT, tree);
    if (!fs.existsSync(base)) continue;
    for (const subject of fs.readdirSync(base)) {
      for (const name of svgNames(path.join(base, subject, "figures"))) {
        const f = path.join(base, subject, "figures", name);
        snap[`${tree}/${subject}/figures/${name}`] = md5(fs.readFileSync(f));
      }
    }
  }
  return snap;
}

const before = snapshotShipped();

section("1. every generator reproduces the figures shipped in both trees");
for (const gen of GENERATORS) {
  const sb = makeSandbox();
  sandboxes.push(sb);
  gen.prepare(sb);
  const run = runGenerator(gen, sb);
  if (!run.ok) {
    ok(false, `${gen.generator} failed to run: ${String(run.out).trim().split("\n").slice(-3).join(" | ")}`);
    continue;
  }
  const { checked, mismatches } = compare(gen, sb);
  totalFigures += checked;
  ok(mismatches.length === 0 && checked > 0,
     `${gen.subject}: ${gen.generator} reproduces all ${checked} shipped figure(s) in both trees` +
     (mismatches.length ? `\n         ${mismatches.join("\n         ")}` : ""));
  console.log(`       (${String(run.out).trim().split("\n").filter((l) => l.startsWith("wrote")).join("; ") || "ran"})`);
}

section("2. the figure family is fully accounted for (no silent gaps)");
const subjectsWithFigures = fs
  .readdirSync(path.join(ROOT, CONTENT))
  .filter((s) => svgNames(path.join(ROOT, CONTENT, s, "figures")).length > 0)
  .sort();
const generatedSubjects = GENERATORS.map((g) => g.subject).sort();
const uncovered = {};
for (const s of subjectsWithFigures) {
  if (!generatedSubjects.includes(s)) uncovered[s] = svgNames(path.join(ROOT, CONTENT, s, "figures"));
}
eq(Object.keys(uncovered).sort(), Object.keys(KNOWN_NO_GENERATOR).sort(),
   "exactly the expected subjects have no generator");
for (const [s, waive] of Object.entries(KNOWN_NO_GENERATOR)) {
  eq(uncovered[s] || [], waive.files,
     `${s}: its ${waive.files.length} shipped figure(s) are the waived, generator-less set`);
  console.log(`       (${s}: ${waive.reason})`);
}
const covered = subjectsWithFigures.filter((s) => generatedSubjects.includes(s));
console.log(`       covered by a generator: ${covered.join(", ")}`);
console.log(`       waived (no generator): ${Object.keys(KNOWN_NO_GENERATOR).join(", ")}`);
ok(subjectsWithFigures.length === covered.length + Object.keys(KNOWN_NO_GENERATOR).length,
   `every subject that ships figures is covered or explicitly waived (${subjectsWithFigures.length} subjects)`);

section("3. the run did not touch the shipped figures (non-destructiveness, asserted)");
const after = snapshotShipped();
eq(Object.keys(after).length, Object.keys(before).length, "the same figures exist after the run");
const touched = Object.keys(before).filter((k) => after[k] !== before[k]);
eq(touched, [], `no shipped figure was modified by running the generators (${Object.keys(before).length} checked)`);
for (const sb of sandboxes) {
  ok(sb.startsWith(os.tmpdir()), `sandbox ${path.basename(sb)} is inside ${os.tmpdir()}`);
}
console.log("       (every generator got an explicit output dir; --trees is never passed. If a generator");
console.log("        were run in a tree-writing mode, the md5 comparison above would fail.)");

if (RED_CONTROL) {
  section("4. RED CONTROL — perturb a generator and prove the guard bites");
  // (a) the incident itself: move H&SB's lower mitochondrion by 1px in a sandboxed COPY of the
  //     generator, and require exactly the cell figure to be reported as drifted.
  const sb = makeSandbox();
  sandboxes.push(sb);
  fs.mkdirSync(path.join(sb, "tools"), { recursive: true });
  const src = fs.readFileSync(path.join(ROOT, "tools/gen-human-social-biology-figures.py"), "utf-8");
  // Locate the line rather than hard-coding a coordinate: the shipped y differs between main and
  // the #179 branch, and a red control that only works on one of them proves nothing.
  const m = src.match(/mitochondrion\(352, (\d+), 100, 48\)/);
  ok(m !== null, "red control: found the H&SB lower-mitochondrion line to perturb");
  const needle = m ? m[0] : null;
  const perturbed = m ? src.replace(needle, `mitochondrion(352, ${Number(m[1]) + 1}, 100, 48)`) : src;
  ok(perturbed !== src, `red control: the perturbation changed the generator source (${needle} -> y+1)`);
  const copy = path.join(sb, "tools", "gen-human-social-biology-figures.py");
  fs.writeFileSync(copy, perturbed);
  const hsb = GENERATORS.find((g) => g.subject === "human-social-biology");
  const redGen = { ...hsb, cmd: (s) => ["python3", [copy, "--repo", ROOT, "--out", hsb.outDir(s)]] };
  hsb.prepare(sb);
  const run = runGenerator(redGen, sb);
  ok(run.ok, "red control: the perturbed generator still runs (so the failure is the comparison, not a crash)");
  const { mismatches } = compare(redGen, sb, "[red] ");
  const cellDrift = mismatches.filter((m) => m.includes("hsb-plant-and-animal-cell.svg") && m.includes("DRIFTED"));
  ok(cellDrift.length > 0,
     "red control: the guard catches drift in hsb-plant-and-animal-cell.svg (the PR #179 defect shape)");
  ok(cellDrift.length === mismatches.length && mismatches.length === 2,
     `red control: and only that figure drifts, in both trees (${mismatches.length} mismatch(es))`);
  for (const m of mismatches) console.log(`         ${m}`);
  // (b) every generator's comparison path bites: flip one byte of one generated file.
  for (const gen of GENERATORS) {
    const s = makeSandbox();
    sandboxes.push(s);
    gen.prepare(s);
    const r = runGenerator(gen, s);
    if (!r.ok) { ok(false, `red control: ${gen.generator} could not be run for the byte-flip probe`); continue; }
    const dir = gen.outDir(s);
    const name = svgNames(dir)[0];
    const f = path.join(dir, name);
    const buf = fs.readFileSync(f);
    buf[buf.length - 3] = buf[buf.length - 3] ^ 0x01; // one byte, inside the trailing newline region
    fs.writeFileSync(f, buf);
    const { mismatches: m2 } = compare(gen, s, "[red] ");
    ok(m2.some((x) => x.includes(name) && x.includes("DRIFTED")),
       `red control: a one-byte change to ${name} is caught for ${gen.generator}`);
  }
}

for (const sb of sandboxes) fs.rmSync(sb, { recursive: true, force: true });

console.log(`\nfigures reproduced by their generators: ${totalFigures}`);
console.log(`runtime: ${((Date.now() - started) / 1000).toFixed(1)}s`);
console.log(`\n${pass} passed, ${fail} failed`);
if (fail > 0) {
  console.log("\nA drift here means a generator no longer reproduces the shipped figure. Re-run the");
  console.log("generator (in its temp-output mode), or fix the generator — never hand-edit the SVG");
  console.log("to match the generator, which is what this harness exists to prevent.");
}
process.exit(fail === 0 ? 0 : 1);
