#!/usr/bin/env node
// Figure generators are part of the figure.
//
// WHY THIS EXISTS
// The rule "generators must be byte-reproducible" was convention, not a gate. In PR #179 a merged
// artwork fix was undone in the generator of record and nothing noticed: no harness regenerated or
// checked any figure, so a normal repo action could silently revert a fix into a live lesson. This
// harness turns that convention into a gate: it re-runs every figure generator and byte-compares its
// output against the SVGs actually committed in both trees.
//
// WHAT IT PROVES
//   - for every subject that HAS a generator, re-running that generator reproduces the shipped
//     `content/<subject>/figures/*.svg` and `public/content/<subject>/figures/*.svg` byte for byte —
//     BOTH trees, asserted per tree, so a figure lost from one tree is a failure and not a half-pass;
//   - the set of shipped figures is exactly accounted for: every figure is either generated by the
//     subject's generator, or named in KNOWN_NO_GENERATOR below with a reason. A new figure that
//     nothing generates FAILS this harness until someone either writes its generator or waives it —
//     so coverage can only grow deliberately;
//   - the run is non-destructive: the shipped figures are snapshotted before and after, and any figure
//     whose bytes changed fails the run (and an empty snapshot fails it too, so the comparison cannot
//     pass by comparing nothing);
//   - AND, since 2026-11-21, that the checks above actually BITE. Every control in RED_CONTROLS mutates
//     the state the real checks read — a perturbed generator, a one-byte flip in generated output, a
//     figure added to or deleted from a sandboxed copy of the two trees, a generator that produces
//     nothing or crashes, a subject with figures and no generator, a waiver naming the wrong files, a
//     figure touched mid-run, a snapshot that comes back empty — and then re-runs `runChecks` itself.
//     A control counts only when the run fails ON THE ASSERTION THAT CONTROL IS AIMED AT (RED_EXPECT
//     below, or the pins the control returns for a figure name it can only know at run time); a control
//     caught by some OTHER failure is reported as caught by the wrong assertion and reds the run.
//     Before this, the controls called `compare()` directly and never ran the harness's own
//     assertions: deleting §1's `check(mismatches.length === 0 && checked > 0, ...)` left the harness
//     green with all eight controls still reporting "caught", and all six byte-flips still passed with
//     the tree loop reduced to `[CONTENT]`. Both of those mutations now red this harness.
//
// WHAT IT DOES NOT PROVE (read this before trusting a green run)
//   - It proves the generators reproduce the CURRENTLY COMMITTED figures. That is NOT the same as
//     proving those figures are correct: a wrong-but-reproducible figure passes here. Geometry
//     correctness is a different instrument (see tools/check-lesson-figures.mjs for the schema and
//     the containment tooling under docs/screenshots/shared-cell-artwork/ for the artwork).
//   - It cannot see a figure that was hand-edited to match no generator: that shows up as a
//     mismatch (good) only for subjects that have a generator. For a subject in
//     KNOWN_NO_GENERATOR there is nothing to reproduce against, so its figures are unverified here.
//   - It cannot see a subject with ZERO figures at all. A subject with no `figures/` directory is
//     simply absent from §2's population, so "every subject that should have figures has one" is a
//     claim no run of this file can make — which is exactly how Mathematics sat in neither the
//     GENERATORS list nor the waiver for months. The controls cannot synthesise it either: an
//     `uncovered-subject` control can only add a figure, never take away the reason to look.
//   - It does not check that a figure is referenced by a lesson, assembled into a page, or rendered.
//   - It would not notice a generator that is wrong in the same way in both trees (they are
//     compared to each other's sources and to the generator, not to an independent oracle).
//   - Runtime is seconds; see the tail of the run for the measured cost.
//
// Non-destructive by construction: every generator is invoked with an explicit output directory
// inside a temp sandbox, and the sandboxes are removed afterwards in a `finally` (the controls always
// run now, so cleanup cannot sit at the end of the happy path). The harness refuses to run a
// generator in a mode that writes the trees (see runGenerator: --trees is never passed, and the
// generators whose default mode writes the trees are always given an explicit output).
//
// Usage:
//   node tools/check-figure-generators.mjs                       # the real check AND every red control
//   node tools/check-figure-generators.mjs --red-control <name>   # one red control, on its own
//   node tools/check-figure-generators.mjs --no-red-control       # the real check only (the one opt-out)
//
// The controls run BY DEFAULT because the suite (tools/check-all.sh, i.e. `npm test`) passes no
// arguments to any harness: a guard behind a flag the suite never passes is not a guard. One exit code
// covers both halves — a failing real check and an uncaught (or mis-aimed) control are both red.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const CONTENT = "content";
const PUBLIC = "public/content";
const TREES = [CONTENT, PUBLIC];

const md5 = (buf) => crypto.createHash("md5").update(buf).digest("hex");
const readSvg = (p) => (fs.existsSync(p) ? fs.readFileSync(p) : null);
const svgNames = (dir) =>
  (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort() : []);
const readEntries = (dir) =>
  svgNames(dir).map((name) => ({ name, md5: md5(fs.readFileSync(path.join(dir, name))) }));

